create or replace function public.consume_constancce_rate_limit(p_key text,p_limit integer,p_window_seconds integer)
returns boolean language plpgsql security definer set search_path=public as $$
declare v_hits integer; v_window interval;
begin
  if length(coalesce(p_key,''))<12 or p_limit<1 or p_limit>5000 or p_window_seconds<1 or p_window_seconds>86400 then return false; end if;
  v_window:=make_interval(secs=>p_window_seconds);
  insert into public.constancce_rate_limits(rate_key,window_started_at,hits,updated_at)
  values(p_key,now(),1,now())
  on conflict(rate_key) do update set
    window_started_at=case when public.constancce_rate_limits.window_started_at < now()-v_window then now() else public.constancce_rate_limits.window_started_at end,
    hits=case when public.constancce_rate_limits.window_started_at < now()-v_window then 1 else public.constancce_rate_limits.hits+1 end,
    updated_at=now()
  returning hits into v_hits;
  return v_hits<=p_limit;
end;
$$;
revoke all on function public.consume_constancce_rate_limit(text,integer,integer) from public,anon,authenticated;
grant execute on function public.consume_constancce_rate_limit(text,integer,integer) to service_role;
