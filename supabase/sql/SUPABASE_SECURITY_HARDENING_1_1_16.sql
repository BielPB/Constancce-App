create or replace function public.add_constancce_friend(p_email text)
returns jsonb language plpgsql security definer set search_path=public,auth as $$
declare v_me uuid:=auth.uid(); v_friend uuid; v_existing bigint; v_allowed boolean;
begin
  if v_me is null or not public.constancce_email_verified() then raise exception 'unauthorized'; end if;
  if length(trim(coalesce(p_email,'')))<5 or length(trim(p_email))>254 or position('@' in p_email)<2 then raise exception 'invalid email'; end if;
  select public.consume_constancce_rate_limit('friend:'||v_me::text,20,86400) into v_allowed;
  if not coalesce(v_allowed,false) then raise exception 'too many requests'; end if;
  select p.user_id into v_friend
  from public.constancce_profiles p join auth.users u on u.id=p.user_id and u.email_confirmed_at is not null
  where lower(p.email)=lower(trim(p_email)) limit 1;
  if v_friend is null then raise exception 'user not found'; end if;
  if v_friend=v_me then raise exception 'cannot add yourself'; end if;
  select id into v_existing from public.constancce_friendships
  where (requester_id=v_me and addressee_id=v_friend) or (requester_id=v_friend and addressee_id=v_me) limit 1;
  if v_existing is not null then raise exception 'friendship already exists'; end if;
  insert into public.constancce_friendships(requester_id,addressee_id,status) values(v_me,v_friend,'pending');
  return jsonb_build_object('ok',true);
end;
$$;

create or replace function public.get_constancce_friends()
returns table(friendship_id bigint,user_id uuid,email text,display_name text,avatar_data_url text,level integer,rank_name text,xp integer,score integer,streak_current integer,streak_best integer,status text,direction text)
language sql security definer set search_path=public,auth stable as $$
  select f.id,p.user_id,p.email,p.display_name,p.avatar_data_url,p.level,p.rank_name,p.xp,p.score,p.streak_current,p.streak_best,f.status,
  case when f.requester_id=auth.uid() then 'sent' else 'received' end
  from public.constancce_friendships f
  join public.constancce_profiles p on p.user_id=case when f.requester_id=auth.uid() then f.addressee_id else f.requester_id end
  where public.constancce_email_verified() and (f.requester_id=auth.uid() or f.addressee_id=auth.uid())
  order by case when f.status='pending' then 0 else 1 end,p.xp desc,f.created_at desc;
$$;

create or replace function public.respond_constancce_friend(p_friendship_id bigint,p_accept boolean)
returns jsonb language plpgsql security definer set search_path=public,auth as $$
begin
  if auth.uid() is null or not public.constancce_email_verified() then raise exception 'unauthorized'; end if;
  if p_accept then
    update public.constancce_friendships set status='accepted',updated_at=now()
    where id=p_friendship_id and addressee_id=auth.uid() and status='pending';
  else
    delete from public.constancce_friendships where id=p_friendship_id and addressee_id=auth.uid() and status='pending';
  end if;
  if not found then raise exception 'friend request not found'; end if;
  return jsonb_build_object('ok',true);
end;
$$;

create or replace function public.remove_constancce_friend(p_friendship_id bigint)
returns jsonb language plpgsql security definer set search_path=public,auth as $$
begin
  if auth.uid() is null or not public.constancce_email_verified() then raise exception 'unauthorized'; end if;
  delete from public.constancce_friendships where id=p_friendship_id and (requester_id=auth.uid() or addressee_id=auth.uid());
  if not found then raise exception 'friendship not found'; end if;
  return jsonb_build_object('ok',true);
end;
$$;

