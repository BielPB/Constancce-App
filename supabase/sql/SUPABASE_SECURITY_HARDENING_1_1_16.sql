-- PRO temporário só pode ser concedido administrativamente E para e-mail confirmado.
create or replace function public.grant_constancce_pro(user_email text, access_days integer default 30)
returns text language plpgsql security definer set search_path = public, auth as $$
declare
  v_id uuid;
  v_confirmed timestamptz;
  v_plan text;
begin
  if access_days < 1 or access_days > 365 then return 'Quantidade de dias inválida'; end if;
  select id,email_confirmed_at into v_id,v_confirmed
  from auth.users where lower(email)=lower(trim(user_email)) limit 1;
  if v_id is null then return 'Usuário não encontrado'; end if;
  if v_confirmed is null then return 'E-mail ainda não confirmado'; end if;
  select plan into v_plan from public.constancce_access where user_id=v_id;
  if v_plan='lifetime' then return 'Usuário já possui PRO vitalício'; end if;
  insert into public.constancce_access(user_id,plan,trial_started_at,trial_ends_at,payment_status,updated_at)
  values(v_id,'trial',now(),now()+make_interval(days=>access_days),'complimentary_trial',now())
  on conflict(user_id) do update set
    plan='trial', trial_started_at=now(), trial_ends_at=now()+make_interval(days=>access_days),
    payment_status='complimentary_trial', updated_at=now();
  return 'PRO temporário liberado com sucesso';
end;
$$;
revoke all on function public.grant_constancce_pro(text,integer) from public, anon, authenticated;
grant execute on function public.grant_constancce_pro(text,integer) to service_role;

