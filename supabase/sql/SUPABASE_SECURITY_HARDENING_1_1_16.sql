create or replace function public.constancce_email_verified()
returns boolean
language sql
stable
security definer
set search_path = auth, public
as $$
  select exists(
    select 1 from auth.users
    where id = auth.uid() and email_confirmed_at is not null
  );
$$;
revoke all on function public.constancce_email_verified() from public, anon;
grant execute on function public.constancce_email_verified() to authenticated;

